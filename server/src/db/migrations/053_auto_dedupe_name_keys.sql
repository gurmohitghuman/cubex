-- The company and person name cleaners read some names differently from here
-- on: emoji dropped, full-width letters, digits and punctuation read as plain
-- ones, placeholders such as "n/a" left blank (no key: they never match), a
-- bracket that never closes cut off, and in company names a closing bracket
-- that closes nothing dropped at either end (one that ends an emoticon, as in
-- "Acme :)", stays). Auto-dedupe keeps each row's key (auto_dedupe_keys) as the
-- cleaner of its day read it, so a key kept from before could miss a new row
-- holding the same value. Settings matching on company or person_name build
-- their keys again, as a new setting does (services/auto-dedupe-index.ts):
-- every row is read again from the start, rows arriving meanwhile are checked
-- once it is done, and building removes no row. Their shared_rows (rows
-- sharing a key with an older row) is cleared, as a new setting's is, and
-- counted again with the new keys once they are built.
UPDATE auto_dedupe SET build_cursor = 0, shared_rows = NULL WHERE match IN ('company', 'person_name');
